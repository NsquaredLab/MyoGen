# Data Loading Functions
# -----------------------


def load_simulation_data(results_path, muscle_type, mvc_levels, study_prefix=""):
    """
    Load ISI/CV data for multiple MVC levels from CSV files.

    Parameters
    ----------
    results_path : Path
        Path to results directory containing CSV files.
    muscle_type : str
        Muscle type identifier (e.g., "VLVM", "TA", "FDI").
    mvc_levels : list of int
        List of MVC levels to load (e.g., [5, 15, 30]).
    study_prefix : str, optional
        Study prefix for file naming (e.g., "VLVM_")

    Returns
    -------
    dict
        Dictionary mapping {mvc_level: DataFrame} with columns:
        - MU_ID: Motor unit identifier
        - mean_firing_rate_Hz: Mean firing rate in Hz
        - CV_ISI: Coefficient of variation of inter-spike intervals
    """
    data_dict = {}

    for mvc in mvc_levels:
        file_path = results_path / f"{study_prefix}isi_cv_data_{muscle_type}_{mvc}.csv"
        if file_path.exists():
            df = pd.read_csv(file_path)
            data_dict[mvc] = df
            print(f"✓ Loaded {len(df)} motor units for {mvc}% MVC from {file_path.name}")
        else:
            print(f"✗ File not found: {file_path}")
            print(f"  Expected: {file_path.name}")

    return data_dict


def load_experimental_data(csv_path):
    """
    Load experimental ISI statistics from CSV file.

    Parameters
    ----------
    csv_path : Path
        Path to ISI_statistics.csv file.

    Returns
    -------
    pd.DataFrame
        Experimental data with columns including:
        - Muscle: Muscle identifier
        - Force Level: Force level (%)
        - FR mean: Mean firing rate (pps)
        - ISI CV: Coefficient of variation
    """
    if csv_path.exists():
        df = pd.read_csv(csv_path)
        print(f"✓ Loaded experimental data: {len(df)} records")
        return df
    else:
        print(f"✗ Experimental data file not found: {csv_path}")
        return None


