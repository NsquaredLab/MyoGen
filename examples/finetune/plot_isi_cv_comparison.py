# Main Execution
# --------------


def main():
    """Main execution function."""
    parser = argparse.ArgumentParser(
        description="Plot ISI/CV comparison for multiple MVC levels"
    )
    parser.add_argument(
        "--muscle",
        type=str,
        default=MUSCLE_TYPE,
        help=f"Muscle type (default: {MUSCLE_TYPE})",
    )
    parser.add_argument(
        "--mvc-levels",
        type=int,
        nargs="+",
        default=MVC_LEVELS,
        help=f"MVC levels to plot (default: {MVC_LEVELS})",
    )
    parser.add_argument(
        "--results-path",
        type=Path,
        default=RESULTS_PATH,
        help=f"Path to results directory (default: {RESULTS_PATH})",
    )
    parser.add_argument(
        "--output-format",
        type=str,
        default="jpg",
        choices=["jpg", "png", "svg", "pdf"],
        help="Output format for figures (default: jpg)",
    )
    parser.add_argument(
        "--study-prefix",
        type=str,
        default="",
        help="Study prefix for file naming (default: none)",
    )

    args = parser.parse_args()

    print("=" * 70)
    print("ISI/CV Comparison Plot")
    print("=" * 70)
    print(f"  Muscle: {args.muscle}")
    print(f"  MVC Levels: {args.mvc_levels}")
    print(f"  Output Format: {args.output_format.upper()}")

    # Load simulation data
    print("\n📂 Loading simulation data...")
    sim_data = load_simulation_data(
        args.results_path, args.muscle, args.mvc_levels, args.study_prefix
    )

    if not sim_data:
        print(
            "\n❌ No simulation data found. Please run extract_isi_and_cv_per_ramps.py first."
        )
        exit(1)

    # Load experimental data
    print("\n📂 Loading experimental data...")
    exp_csv_path = Path(__file__).parent / "ISI_statistics.csv"
    exp_data = load_experimental_data(exp_csv_path)

    # Generate markers for MVC levels (colors are based on recruitment order)
    mvc_markers = generate_mvc_markers(args.mvc_levels)
    print(f"\n🎨 Generated {len(args.mvc_levels)} distinct marker shapes")

    # Create comparison plot
    print("\n📊 Creating comparison plot...")
    fig, ax = plot_cv_vs_fr_comparison(
        sim_data, exp_data, args.muscle, mvc_markers, EXP_COLORS
    )

    # Save figure with specified format
    output_file = (
        args.results_path
        / f"{args.study_prefix}isi_cv_comparison_{args.muscle}.{args.output_format}"
    )
    plt.tight_layout()

    # Set quality based on format
    if args.output_format in ["jpg", "jpeg"]:
        plt.savefig(output_file, dpi=300, bbox_inches="tight", pil_kwargs={"quality": 95})
    else:
        plt.savefig(output_file, dpi=300, bbox_inches="tight", transparent=True)

    print(f"\n✅ Plot saved to: {output_file}")

    # Print summary statistics
    print("\n" + "=" * 70)
    print("📊 SUMMARY STATISTICS")
    print("=" * 70)

    for mvc_level in sorted(sim_data.keys()):
        df = sim_data[mvc_level]
        print(f"\n{mvc_level}% MVC ({args.muscle}):")
        print(f"  Motor units (N):      {len(df)}")
        print(
            f"  Mean firing rate:     {df['mean_firing_rate_Hz'].mean():.2f} ± {df['mean_firing_rate_Hz'].std():.2f} Hz"
        )
        print(
            f"  Mean CV:              {df['CV_ISI'].mean():.3f} ± {df['CV_ISI'].std():.3f}"
        )
        print(
            f"  FR range:             {df['mean_firing_rate_Hz'].min():.2f} - {df['mean_firing_rate_Hz'].max():.2f} Hz"
        )
        print(
            f"  CV range:             {df['CV_ISI'].min():.3f} - {df['CV_ISI'].max():.3f}"
        )

    print("\n" + "=" * 70)
    print("✅ Analysis complete!")
    print("=" * 70)


if __name__ == "__main__":
    main()
