# Muscle type to analyze
MUSCLE_TYPE = "VLVM"  # Options: "VLVM", "TA", "FDI"

# MVC levels to include in comparison (can be any number of levels)
MVC_LEVELS = [5, 15, 30]

# Path to results directory
RESULTS_PATH = Path("./results")

# Experimental data colors (all gray)
EXP_COLORS = {"VM": "#808080", "VL": "#808080", "TA": "#808080", "FDI": "#808080"}

# Available marker styles (will cycle through these)
AVAILABLE_MARKERS = ["o", "s", "^", "v", "D", "p", "*", "h", "<", ">", "d", "P", "X"]


def generate_mvc_markers(mvc_levels):
    """
    Generate marker mappings for any number of MVC levels.

    Colors are handled by the viridis colormap based on recruitment order.
    This function only assigns distinct marker shapes for each MVC level.

    Parameters
    ----------
    mvc_levels : list of int
        List of MVC levels (e.g., [5, 10, 15, 30, 50])

    Returns
    -------
    dict
        mvc_markers - dictionary mapping mvc_level to marker shape
    """
    mvc_markers = {}

    for i, mvc in enumerate(sorted(mvc_levels)):
        # Assign marker (cycle through available markers)
        mvc_markers[mvc] = AVAILABLE_MARKERS[i % len(AVAILABLE_MARKERS)]

    return mvc_markers

