# Plotting Function
# -----------------


def plot_cv_vs_fr_comparison(
    sim_data_dict, exp_data, muscle_type, mvc_markers, exp_colors
):
    """
    Create CV vs FR plot comparing simulated MVC levels with experimental data.

    This function creates a publication-ready scatter plot showing the relationship
    between coefficient of variation (CV) and mean firing rate. Experimental data
    is shown with convex hulls and scatter markers, while simulated data for each
    MVC level is shown with distinct colors based on recruitment order.

    Parameters
    ----------
    sim_data_dict : dict
        Dictionary {mvc_level: DataFrame} with simulation data.
    exp_data : pd.DataFrame
        Experimental ISI statistics.
    muscle_type : str
        Muscle type being analyzed.
    mvc_markers : dict
        Marker styles for each MVC level {mvc_level: marker}.
    exp_colors : dict
        Colors for experimental muscles {muscle: color}.

    Returns
    -------
    tuple
        (fig, ax) matplotlib figure and axis objects.
    """
    fig, ax = plt.subplots(figsize=(8, 6))

    # 1. Plot experimental data (convex hulls + scatter)
    if exp_data is not None:
        muscles = exp_data["Muscle"].unique()
        for muscle in muscles:
            # Skip FDI data
            if muscle == "FDI":
                continue

            muscle_data = exp_data[exp_data["Muscle"] == muscle]
            cv_data = muscle_data["ISI CV"].values
            fr_data = muscle_data["FR mean"].values

            # Draw convex hull for experimental data
            if len(cv_data) > 2:
                points = np.column_stack([cv_data, fr_data])
                try:
                    hull = ConvexHull(points)
                    hull_points = points[hull.vertices]
                    polygon = Polygon(
                        hull_points,
                        facecolor=exp_colors.get(muscle, "#000000"),
                        alpha=0.25,
                        edgecolor=exp_colors.get(muscle, "#000000"),
                        linewidth=1.5,
                        linestyle="-",
                        zorder=0,
                    )
                    ax.add_patch(polygon)
                except Exception:
                    # Skip if convex hull cannot be computed
                    pass

            # Scatter points for experimental data (no label for legend)
            ax.scatter(
                cv_data,
                fr_data,
                s=20,
                alpha=1.0,
                color=exp_colors.get(muscle, "#000000"),
                edgecolors="white",
                linewidth=0.5,
                marker="x",
                zorder=1,
            )

    # 2. Plot simulated data for each MVC level (colored by recruitment order)
    # Track global min/max recruitment order for consistent colorbar
    all_recruitment_orders = []

    for mvc_level in sorted(sim_data_dict.keys()):
        df = sim_data_dict[mvc_level]

        # Extract recruitment order from MU_ID (assuming MU_ID = recruitment order)
        # If MU_ID doesn't exist, create from index
        if "MU_ID" in df.columns:
            recruitment_order = df["MU_ID"].values
        else:
            recruitment_order = np.arange(len(df))

        all_recruitment_orders.extend(recruitment_order)

        # Normalize recruitment order to [0, 1] for colormap
        norm_recruitment = (recruitment_order - recruitment_order.min()) / (
            recruitment_order.max() - recruitment_order.min() + 1e-10
        )

        # Use rainbow colormap to color by recruitment order
        colors = plt.cm.rainbow(norm_recruitment)

        # Plot with recruitment order coloring and MVC-specific marker
        ax.scatter(
            df["CV_ISI"],
            df["mean_firing_rate_Hz"],
            s=50,
            alpha=0.8,
            c=colors,
            label=f"{mvc_level}%",
            edgecolors="black",
            linewidth=0.6,
            marker=mvc_markers.get(mvc_level, "o"),  # Use MVC-specific marker
            zorder=2,
        )

    # Add colorbar for recruitment order
    if all_recruitment_orders:
        min_recruitment = int(np.min(all_recruitment_orders))
        max_recruitment = int(np.max(all_recruitment_orders))

        # Create ScalarMappable for colorbar
        norm = Normalize(vmin=min_recruitment, vmax=max_recruitment)
        sm = ScalarMappable(cmap="rainbow", norm=norm)
        sm.set_array([])

        # Add colorbar
        cbar = plt.colorbar(sm, ax=ax, pad=0.02, aspect=30)
        cbar.set_label(
            "Recruitment Order (MU #)", fontsize=10, rotation=270, labelpad=20
        )
        cbar.ax.tick_params(labelsize=9)

    # 3. Format plot
    ax.set_xlabel("Coefficient of Variation (CV)", fontsize=12)
    ax.set_ylabel("Mean Firing Rate (pps)", fontsize=12)
    ax.set_xlim(0, 0.5)
    ax.set_ylim(4, 25)
    ax.set_title(f"ISI Statistics Comparison - {muscle_type}", fontsize=14)
    ax.tick_params(axis="both", labelsize=10)
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    sns.despine(ax=ax, offset=10, trim=True)

    return fig, ax


